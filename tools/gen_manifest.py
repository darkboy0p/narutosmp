#!/usr/bin/env python3
"""Generates ASSET_MANIFEST.md from the actual resource pack and plugin source.
Kinds: 3D MODEL = item model with element geometry; flat sprite model = parent item/generated (NOT 3D); 2D texture; animated 2D
texture; item-model definition (items/*.json); font; metadata. 'Used by gameplay' is determined from Java source references.
'Verified in-game' is always 'no': nothing here can observe a running Minecraft client."""
import json, os, re, struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "resourcepack"))
NS = os.path.join(ROOT, "assets", "shinobi")
JAVA = os.path.join(HERE, "..", "src", "main", "java", "dev", "shinobi")
java_src = "".join(open(os.path.join(JAVA, f)).read() for f in os.listdir(JAVA) if f.endswith(".java"))

def png_size(p):
    with open(p, "rb") as f: d = f.read(24)
    return struct.unpack(">II", d[16:24]) if d[:8] == b"\x89PNG\r\n\x1a\n" else None

models = {}
for fn in os.listdir(os.path.join(NS, "models", "item")):
    models[fn[:-5]] = json.load(open(os.path.join(NS, "models", "item", fn)))
item_defs = {fn[:-5] for fn in os.listdir(os.path.join(NS, "items"))}
used_tex = set()
for m in models.values():
    for t in m.get("textures", {}).values():
        if t.startswith("shinobi:"): used_tex.add(t.split(":")[1])
used_font = set()
for p in json.load(open(os.path.join(NS, "font", "hud.json")))["providers"]:
    if p["type"] == "bitmap": used_font.add(p["file"].split(":")[1])

def gameplay_use(name):
    if name.startswith("headgear_"): return "HeadgearManager (worn display)" if "HeadgearRules.modelId" in java_src else "no"
    if name.startswith("orb_"): return "ChargeVisuals.orb (charging)" if '"orb_" + kind' in java_src else "no"
    if name == "headgear": return "HeadgearManager via headgear_* models"
    if name.startswith("orb_"): return "ChargeVisuals.orb"
    return "item/GUI sprite via setItemModel" if name in item_defs else ""

def assoc(name):
    n = name.lower()
    for clan in ("uchiha", "hyuga", "senju", "uzumaki", "nara"):
        if clan in n: return clan.capitalize()
    if any(k in n for k in ("sharingan", "mangekyo", "amaterasu", "kamui", "susanoo", "tsukuyomi", "chidori", "fireball", "rinnegan", "eternal", "lightning", "fire")): return "Uchiha / Uchiha-style"
    if any(k in n for k in ("byakugan", "tenseigan", "palm", "gentle")): return "Hyuga"
    if any(k in n for k in ("wood", "sabre")): return "Senju"
    if any(k in n for k in ("chain", "seal", "barrier")): return "Uzumaki"
    if "shadow" in n: return "Nara"
    if any(k in n for k in ("rasengan", "rasenshuriken", "wind", "orb")): return "Naruto techniques"
    return "general"

rows, counts = [], {}
for folder, _, fs in os.walk(ROOT):
    for f in sorted(fs):
        full = os.path.join(folder, f)
        rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
        stem = f.rsplit(".", 1)[0]
        res, ref, kind = "", "", "other"
        if rel == "pack.mcmeta": kind, ref = "metadata", "client"
        elif "/textures/item/" in rel and f.endswith(".png"):
            sz = png_size(full); res = f"{sz[0]}x{sz[1]}"
            kind = "animated 2D texture" if os.path.exists(full + ".mcmeta") else "2D texture"
            ref = "model" if "item/" + stem in used_tex else "ORPHAN"
        elif "/textures/font/" in rel:
            sz = png_size(full); res = f"{sz[0]}x{sz[1]}"; kind = "2D texture (HUD font sheet)"; ref = "font/hud.json" if "font/" + f in used_font else "ORPHAN"
        elif "/models/item/" in rel:
            m = models[stem]
            if "elements" in m: kind = f"3D MODEL (element geometry, {len(m['elements'])} cuboids)"
            else: kind = "flat sprite model (parent item/generated, NOT 3D)"
            ref = "item definition" if stem in item_defs else "ORPHAN"
        elif "/items/" in rel: kind, ref = "item-model definition", "plugin sets item_model"
        elif "/font/" in rel: kind, ref = "font definition", "HUD text"
        elif f.endswith(".mcmeta"): kind, ref = "animation metadata", "texture"
        key = kind.split(" (")[0]
        counts[key] = counts.get(key, 0) + 1
        rows.append((rel, f.rsplit(".", 1)[-1], kind, assoc(stem), res, ref, gameplay_use(stem) if ("/models/item/" in rel or "/items/" in rel or "/textures/item/" in rel) else ""))
rows.sort()
orph = [r for r in rows if r[5] == "ORPHAN"]
out = ["# Asset manifest (generated by tools/gen_manifest.py; do not edit by hand)", "",
       f"Files: {len(rows)}. Orphans (nothing references them): {len(orph)}.", "",
       "## What each kind means", "",
       "- **3D MODEL**: an item model with `elements` (cuboid geometry with per-face UVs). Rendered in the world by `ItemDisplay` entities.",
       "- **flat sprite model**: a 2D icon extruded by the game as an ordinary item. It is **not** a 3D model.",
       "- **2D texture** / **animated 2D texture**: PNG pixel art (animated = frame strip + `.mcmeta`).",
       "- **item-model definition**: `items/*.json`, maps an item_model id to a model.",
       "- **Particles and sounds**: none are resource-pack assets. All particles are vanilla `Particle` types spawned by Java code and all sounds are vanilla `Sound` events (no custom sound files / `sounds.json` exist).",
       "- *Verified in-game* is **no for every asset**. 'Static' checks = `tools/verify_pack.py` (paths, JSON, UV ranges, texture refs).", "",
       "## Counts by kind", "", "| Kind | Files |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(counts.items())] + ["",
       "## Custom 3D models", "", "| Model | Cuboids | Purpose | Used by gameplay code | Verified |", "|---|---|---|---|---|"]
for name in sorted(models):
    if "elements" in models[name]:
        purpose = "worn headband + dojutsu eyes (any helmet)" if name.startswith("headgear_") else "spinning chakra orb while charging" if name.startswith("orb_") else ""
        out.append(f"| `models/item/{name}.json` | {len(models[name]['elements'])} | {purpose} | {gameplay_use(name)} | geometry/UV static checks + orthographic render; not in-game |")
out += ["", "## All files", "",
        "| Path | Format | Kind | Associated (heuristic) | Resolution | Referenced by | Used by gameplay | Verified in-game |", "|---|---|---|---|---|---|---|---|"]
for rel, fmt, kind, a, res, ref, use in rows:
    out.append(f"| `{rel}` | {fmt} | {kind} | {a} | {res} | {ref} | {use} | no |")
out += ["", "## Required by the design documents but NOT created (pending)", "",
        "- **3D models**: Susanoo stages (current Susanoo is built from vanilla BlockDisplay glass, not a custom model), Wood Dragon, Wood Prison, Wood Wall, Uzumaki chains/barriers/sealing circles, Hyuga palm/rotation constructs, Nara shadow tendrils, Kamui vortex, Amaterasu flames, Rasenshuriken blades, Chidori arc model, weapons (kunai/shuriken meshes), scroll 3D models.",
        "- **Animated player models / true head-bone attachment / first-person effects**: need a client mod; none exists.",
        "- **Custom sound files and `sounds.json`**.",
        "- Per-ability HUD/GUI icons for most implemented techniques, bloodline icons, clan-specific headband variants.",
        "- Original Tenseigan art (`eye_tenseigan` is the Byakugan strip hue-shifted)."]
open(os.path.join(HERE, "..", "ASSET_MANIFEST.md"), "w").write("\n".join(out) + "\n")
print("rows", len(rows), "orphans", len(orph), counts)
