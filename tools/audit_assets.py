#!/usr/bin/env python3
"""Audits resourcepack/ and writes docs/ASSET_AUDIT.md from the ACTUAL files (no assumptions).
Per model: type (flat icon vs 3D elements), element count, texture refs, texture size, distinct colours (flat/placeholder
indicator), missing refs. Static analysis only: says nothing about how a model looks in the Minecraft client."""
import json, os, sys
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "resourcepack", "assets", "shinobi"))
rows, problems = [], []
def tex_path(ref):
    return os.path.join(ROOT, "textures", ref.split(":", 1)[-1].replace("shinobi/", "", 1) + ".png") if ref.startswith(("shinobi:", "item/")) or True else None
def resolve(ref):
    r = ref.split(":", 1)[-1]
    return os.path.join(ROOT, "textures", r[len("item/"):] if False else r) + ".png"
tex_cache = {}
def tex_info(ref):
    p = resolve(ref)
    if p in tex_cache: return tex_cache[p]
    if not os.path.exists(p): tex_cache[p] = None; return None
    im = Image.open(p).convert("RGBA")
    colors = len(set(im.getdata()))
    tex_cache[p] = (im.size, colors)
    return tex_cache[p]
used = set()
for f in sorted(os.listdir(os.path.join(ROOT, "models", "item"))):
    m = json.load(open(os.path.join(ROOT, "models", "item", f)))
    name = f[:-5]
    els = m.get("elements", [])
    kind = "3D elements" if els else ("flat icon" if m.get("parent", "").endswith("generated") else "other:" + m.get("parent", "?"))
    texs = list((m.get("textures") or {}).values())
    infos = []
    for t in texs:
        used.add(resolve(t))
        i = tex_info(t)
        if i is None: problems.append(f"{name}: missing texture {t}")
        else: infos.append(i)
    faces = sum(len(e.get("faces", {})) for e in els)
    uv_missing = sum(1 for e in els for fc in e.get("faces", {}).values() if "uv" not in fc)
    size = "/".join(f"{i[0][0]}x{i[0][1]}" for i in infos) or "-"
    cols = min((i[1] for i in infos), default=0)
    flags = []
    if kind == "flat icon" and infos and cols <= 4: flags.append("near-flat colour (placeholder-like)")
    if kind == "flat icon" and infos and cols <= 12: flags.append("low detail")
    if els and uv_missing: flags.append(f"{uv_missing} faces without explicit uv")
    if not infos: flags.append("no resolvable texture")
    rows.append((name, kind, len(els), faces, size, cols, "; ".join(flags)))
orphans = sorted(os.path.relpath(os.path.join(d, x), ROOT) for d, _, fs in os.walk(os.path.join(ROOT, "textures")) for x in fs
                 if os.path.join(d, x) not in used and "font" not in d)
def group(n):
    for k, g in [("eye_", "Dojutsu eye icons"), ("headgear_", "Headgear 3D models"), ("orb_", "Charge orbs 3D"), ("scroll_", "Jutsu scrolls"),
                 ("clan_", "Clan emblems"), ("mission_", "Mission icons"), ("nature_", "Chakra natures"), ("gate_", "Gates")]:
        if n.startswith(k): return g
    return "Items / equipment / misc"
out = ["# ASSET AUDIT (generated by tools/audit_assets.py)", "",
       "Static analysis of `resourcepack/` only. **No asset in this inventory has been viewed in the Minecraft client.**",
       "Textures are generated procedurally by `tools/make_pack.py` (pure-Python PNG writer); editing a PNG by hand is overwritten on rebuild.", "",
       f"Models: {len(rows)} | 3D element models: {sum(1 for r in rows if r[1]=='3D elements')} | flat icons: {sum(1 for r in rows if r[1]=='flat icon')}"
       f" | missing refs: {len(problems)} | unreferenced textures: {len(orphans)}", ""]
groups = {}
for r in rows: groups.setdefault(group(r[0]), []).append(r)
for g, rs in groups.items():
    low = sum(1 for r in rs if r[6])
    out += [f"## {g} ({len(rs)} models, {low} flagged)", "", "| model | kind | elements | faces | texture size | colours | flags |", "|---|---|---|---|---|---|---|"]
    out += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} |" for r in rs]
    out.append("")
out += ["## Problems", ""] + ([f"- {p}" for p in problems] or ["- none found by static checks"]) + ["", "## Unreferenced textures", ""] + ([f"- {o}" for o in orphans] or ["- none"])
out += ["", "## Not covered by any asset today (no models/textures exist)", "",
        "Susanoo (all four stages: only state logic exists), Tailed Beasts, Jinchuriki cloaks, Sage Mode markings, Kamui dimension visuals, Wood Release,",
        "sealing chains, shadow techniques, Gentle Fist effects, NPC models/emblems beyond the 5 flat clan icons, custom GUI backgrounds, Fabric-rendered aura.",
        "These need the Fabric companion project (does not exist yet) and new art; they are not redesigned by this audit."]
open(os.path.join(os.path.dirname(__file__), "..", "docs", "ASSET_AUDIT.md"), "w").write("\n".join(out) + "\n")
print("models", len(rows), "problems", len(problems), "orphans", len(orphans), "flagged", sum(1 for r in rows if r[6]))
sys.exit(1 if problems else 0)
